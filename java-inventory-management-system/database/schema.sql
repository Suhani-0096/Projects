CREATE DATABASE IF NOT EXISTS inventory_management;
USE inventory_management;
CREATE TABLE IF NOT EXISTS products (id INT PRIMARY KEY AUTO_INCREMENT,name VARCHAR(100) NOT NULL,category VARCHAR(50) NOT NULL,price DECIMAL(12,2) NOT NULL,quantity INT NOT NULL,supplier VARCHAR(100) NOT NULL,product_type VARCHAR(30) NOT NULL,extra_info VARCHAR(150),created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
